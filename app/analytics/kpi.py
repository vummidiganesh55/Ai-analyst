from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import pandas as pd


@dataclass
class KPIResult:
    name: str
    value: float
    unit: str
    source_columns: list[str]
    description: str
    category: str


class KPIDetectionEngine:
    """
    Deterministic KPI detection and calculation engine.

    The LLM should identify which KPI the user is asking about,
    while this engine performs the actual calculation.
    """

    KPI_ALIASES = {
        "revenue": ["revenue", "sales", "total_sales", "income"],
        "cost": ["cost", "expense", "expenses"],
        "orders": ["orders", "order_count", "order_count_total"],
        "customers": ["customer_id", "customers", "customer_count"],
    }

    def __init__(self, dataframe: pd.DataFrame):
        if not isinstance(dataframe, pd.DataFrame):
            raise TypeError("dataframe must be a pandas DataFrame")

        if dataframe.empty:
            raise ValueError("dataframe cannot be empty")

        self.df = dataframe

    def _find_column(self, aliases: list[str]) -> str | None:
        normalized = {
            str(column).strip().lower(): column
            for column in self.df.columns
        }

        for alias in aliases:
            if alias.lower() in normalized:
                return normalized[alias.lower()]

        return None

    def _require_numeric(self, column: str) -> None:
        if not pd.api.types.is_numeric_dtype(self.df[column]):
            raise TypeError(f"Column '{column}' must be numeric")

    def revenue(self) -> KPIResult | None:
        column = self._find_column(self.KPI_ALIASES["revenue"])

        if column is None:
            return None

        self._require_numeric(column)

        value = float(self.df[column].sum())

        return KPIResult(
            name="Revenue",
            value=value,
            unit="currency",
            source_columns=[column],
            description="Total revenue generated by the dataset",
            category="financial",
        )

    def cost(self) -> KPIResult | None:
        column = self._find_column(self.KPI_ALIASES["cost"])

        if column is None:
            return None

        self._require_numeric(column)

        value = float(self.df[column].sum())

        return KPIResult(
            name="Cost",
            value=value,
            unit="currency",
            source_columns=[column],
            description="Total cost recorded in the dataset",
            category="financial",
        )

    def profit(self) -> KPIResult | None:
        revenue_column = self._find_column(self.KPI_ALIASES["revenue"])
        cost_column = self._find_column(self.KPI_ALIASES["cost"])

        if revenue_column is None or cost_column is None:
            return None

        self._require_numeric(revenue_column)
        self._require_numeric(cost_column)

        value = float(
            self.df[revenue_column].sum()
            - self.df[cost_column].sum()
        )

        return KPIResult(
            name="Profit",
            value=value,
            unit="currency",
            source_columns=[revenue_column, cost_column],
            description="Revenue minus total cost",
            category="financial",
        )

    def margin(self) -> KPIResult | None:
        revenue_column = self._find_column(self.KPI_ALIASES["revenue"])
        cost_column = self._find_column(self.KPI_ALIASES["cost"])

        if revenue_column is None or cost_column is None:
            return None

        self._require_numeric(revenue_column)
        self._require_numeric(cost_column)

        revenue = float(self.df[revenue_column].sum())
        cost = float(self.df[cost_column].sum())

        if revenue == 0:
            return KPIResult(
                name="Margin",
                value=0.0,
                unit="percentage",
                source_columns=[revenue_column, cost_column],
                description="Profit margin based on revenue",
                category="financial",
            )

        value = ((revenue - cost) / revenue) * 100

        return KPIResult(
            name="Margin",
            value=float(value),
            unit="percentage",
            source_columns=[revenue_column, cost_column],
            description="Profit as a percentage of revenue",
            category="financial",
        )

    def orders(self) -> KPIResult | None:
        column = self._find_column(self.KPI_ALIASES["orders"])

        if column is None:
            return None

        self._require_numeric(column)

        value = float(self.df[column].sum())

        return KPIResult(
            name="Orders",
            value=value,
            unit="count",
            source_columns=[column],
            description="Total number of orders",
            category="operations",
        )

    def customers(self) -> KPIResult | None:
        column = self._find_column(self.KPI_ALIASES["customers"])

        if column is None:
            return None

        value = float(self.df[column].nunique())

        return KPIResult(
            name="Customers",
            value=value,
            unit="count",
            source_columns=[column],
            description="Number of unique customers",
            category="customer",
        )

    def aov(self) -> KPIResult | None:
        revenue_column = self._find_column(self.KPI_ALIASES["revenue"])
        orders_column = self._find_column(self.KPI_ALIASES["orders"])

        if revenue_column is None or orders_column is None:
            return None

        self._require_numeric(revenue_column)
        self._require_numeric(orders_column)

        revenue = float(self.df[revenue_column].sum())
        orders = float(self.df[orders_column].sum())

        if orders == 0:
            value = 0.0
        else:
            value = revenue / orders

        return KPIResult(
            name="Average Order Value",
            value=float(value),
            unit="currency",
            source_columns=[revenue_column, orders_column],
            description="Average revenue generated per order",
            category="customer",
        )

    def detect(self) -> list[KPIResult]:
        """
        Detect all KPIs that can be calculated from the dataset.
        """
        calculators = [
            self.revenue,
            self.cost,
            self.profit,
            self.margin,
            self.orders,
            self.customers,
            self.aov,
        ]

        results: list[KPIResult] = []

        for calculator in calculators:
            result = calculator()

            if result is not None:
                results.append(result)

        return results

    def to_dataframe(self) -> pd.DataFrame:
        """
        Convert detected KPIs into a DataFrame.
        """
        results = self.detect()

        return pd.DataFrame(
            [
                {
                    "name": result.name,
                    "value": result.value,
                    "unit": result.unit,
                    "source_columns": result.source_columns,
                    "description": result.description,
                    "category": result.category,
                }
                for result in results
            ]
        )

    def to_dict(self) -> list[dict[str, Any]]:
        """
        Convert detected KPIs into JSON-compatible dictionaries.
        """
        return [
            {
                "name": result.name,
                "value": result.value,
                "unit": result.unit,
                "source_columns": result.source_columns,
                "description": result.description,
                "category": result.category,
            }
            for result in self.detect()
        ]